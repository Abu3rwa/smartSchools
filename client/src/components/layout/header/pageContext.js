export const resolvePageContext = (pathname, role) => {
    const candidates = SHORTCUT_CANDIDATES.filter((item) => !item.roles || item.roles.includes(role));
    const pool = [...candidates, ...PAGE_CATALOG];
    const matches = pool.filter((item) => (
        pathname === item.path || pathname.startsWith(`${item.path}/`)
    ));
    if (matches.length === 0) return null;
    matches.sort((left, right) => right.path.length - left.path.length);
    const best = matches[0];
    return { labelKey: best.labelKey, section: best.section || 'overview' };
};
