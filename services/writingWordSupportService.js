/**
 * Writing word support: the words a student may lean on while writing.
 *
 * Reads only. Nothing here writes to spelling or vocabulary records, calls the
 * AI, or affects a grade. Vocabulary lists are intersected with the lists the
 * student is actually assigned, so a teacher's selection can never widen what a
 * student sees.
 */
import Student from "../models/Student.js";
import SpellingRetestItem from "../models/SpellingRetestItem.js";
import VocabWord from "../models/VocabWord.js";
import { getAssignedLists, resolveSelection } from "./vocabularyService.js";
import { textTokens } from "./writingAssistantLogic.js";

export const SPELLING_MAX_DEFAULT = 5;
export const SPELLING_MAX_LIMIT = 10;
export const VOCABULARY_WORD_LIMIT = 60;

const LIST_ID = /^S\d{1,2}-L\d{1,3}$/;
const normal = (value) =>
  String(value || "")
    .trim()
    .toLowerCase();

const CVC = /[^aeiou][aeiou][^aeiouwxy]$/;
const CONSONANT_Y = /[^aeiou]y$/;

/**
 * Common inflected forms, generated by rule. A form that does not exist in
 * English simply never matches, and the teacher still decides every row.
 */
export const wordForms = (value) => {
  const word = normal(value);
  if (!word || !/^[a-z]{3,}$/.test(word)) return [];
  const forms = new Set();
  const add = (form) => {
    if (form && form !== word) forms.add(form);
  };
  const last = word[word.length - 1];
  if (/(s|x|z|ch|sh)$/.test(word)) add(`${word}es`);
  else if (CONSONANT_Y.test(word)) add(`${word.slice(0, -1)}ies`);
  else add(`${word}s`);

  if (word.endsWith("e")) add(`${word}d`);
  else if (CONSONANT_Y.test(word)) add(`${word.slice(0, -1)}ied`);
  else {
    add(`${word}ed`);
    if (CVC.test(word) && word.length >= 4) add(`${word}${last}ed`);
  }

  if (word.endsWith("e") && !word.endsWith("ee")) add(`${word.slice(0, -1)}ing`);
  else if (CVC.test(word)) add(`${word}${last}ing`);
  else add(`${word}ing`);

  if (word.endsWith("le")) add(`${word.slice(0, -1)}y`);
  else if (CONSONANT_Y.test(word)) add(`${word.slice(0, -1)}ily`);
  else if (word.endsWith("ic")) add(`${word}ally`);
  else add(`${word}ly`);

  if (word.endsWith("e")) {
    add(`${word}r`);
    add(`${word}st`);
  } else if (CONSONANT_Y.test(word)) {
    add(`${word.slice(0, -1)}ier`);
    add(`${word.slice(0, -1)}iest`);
  } else {
    add(`${word}er`);
    add(`${word}est`);
    if (CVC.test(word)) {
      add(`${word}${last}er`);
      add(`${word}${last}est`);
    }
  }
  return [...forms];
};

export const normalizeWordSupport = (input = {}) => {
  const listIds = (Array.isArray(input?.vocabulary?.listIds)
    ? input.vocabulary.listIds
    : []
  )
    .map((id) => String(id || "").trim().toUpperCase())
    .filter((id) => LIST_ID.test(id))
    .filter((id, index, rows) => rows.indexOf(id) === index)
    .slice(0, 24);
  const maxWords = Math.min(
    Math.max(Number(input?.spelling?.maxWords) || SPELLING_MAX_DEFAULT, 1),
    SPELLING_MAX_LIMIT,
  );
  return {
    vocabulary: {
      enabled: input?.vocabulary?.enabled === true && listIds.length > 0,
      listIds,
    },
    spelling: {
      enabled: input?.spelling?.enabled === true,
      maxWords,
    },
  };
};

const disabled = (config) => ({
  enabled: false,
  spelling: {
    ...config.spelling,
    status: "disabled",
    words: [],
  },
  vocabulary: {
    ...config.vocabulary,
    status: "disabled",
    lists: [],
    words: [],
    total: 0,
    shown: 0,
    truncated: false,
  },
});

const spellingWords = async ({
  schoolId,
  studentId,
  config,
  priorTargets,
}) => {
  const maxWords = config.maxWords;
  const rows = [];
  const seen = new Set();
  const push = (row, source) => {
    const key = normal(row?.word ?? row?.wordSnapshot);
    if (!key || seen.has(key)) return;
    seen.add(key);
    const word = String((row?.word ?? row?.wordSnapshot) || "").trim();
    rows.push({
      word,
      grade: row?.grade || "",
      week: Number(row?.week) || 0,
      source,
      forms: wordForms(word),
    });
  };

  // Words a teacher already published on an earlier round come first: the
  // student is being asked to apply them.
  for (const row of priorTargets || []) push(row, "feedback");

  if (rows.length < maxWords) {
    const items = await SpellingRetestItem.find({
      school: schoolId,
      student: studentId,
    })
      .sort({ flaggedAt: -1 })
      .limit(Math.min(maxWords * 4, 40))
      .select("wordSnapshot grade week")
      .lean();
    for (const row of items) {
      if (rows.length >= maxWords) break;
      push(row, "spelling");
    }
  }

  return rows.slice(0, maxWords);
};

/** Round-robin across lists, deduped by word, so no list is crowded out. */
export const interleaveVocabularyBuckets = (buckets = [], limit = 0) => {
  const seen = new Set();
  const rows = [];
  const deepest = buckets.reduce(
    (max, docs) => Math.max(max, (docs || []).length),
    0,
  );
  for (let depth = 0; depth < deepest && rows.length < limit; depth += 1) {
    for (const docs of buckets) {
      if (rows.length >= limit) break;
      const doc = docs[depth];
      if (!doc) continue;
      const key = normal(doc.word);
      if (!key || seen.has(key)) continue;
      seen.add(key);
      rows.push(doc);
    }
  }
  return rows;
};

const emptyVocabulary = () => ({
  lists: [],
  words: [],
  total: 0,
  shown: 0,
  truncated: false,
});

const vocabularyWords = async ({ schoolId, studentId, config }) => {
  const student = await Student.findOne({
    school: schoolId,
    _id: studentId,
  })
    .select("currentClass enrolledClasses")
    .lean();
  if (!student) return emptyVocabulary();

  const assigned = await getAssignedLists({ schoolId, student });
  const allowed = resolveSelection(assigned, {
    listIds: config.listIds,
  });
  if (!allowed.length) return emptyVocabulary();

  const allowedSet = new Set(allowed);
  // Each list keeps its own words; the merge interleaves them, so one long list
  // cannot push the later lists out of the rail.
  const [buckets, uniqueTotal] = await Promise.all([
    Promise.all(
      allowed.map((listId) =>
        VocabWord.find({ school: schoolId, listId })
          .sort({ normalizedWord: 1 })
          .limit(VOCABULARY_WORD_LIMIT)
          .select(
            "listId word baseWord partOfSpeech meaning arabicMeaning exampleSentence",
          )
          .lean(),
      ),
    ),
    VocabWord.distinct("normalizedWord", {
      school: schoolId,
      listId: { $in: allowed },
    }),
  ]);

  const words = interleaveVocabularyBuckets(
    buckets,
    VOCABULARY_WORD_LIMIT,
  ).map((doc) => ({
    word: doc.word,
    baseWord: doc.baseWord || "",
    listId: doc.listId,
    partOfSpeech: Array.isArray(doc.partOfSpeech)
      ? doc.partOfSpeech.join(", ")
      : "",
    meaning: doc.meaning || "",
    arabicMeaning: doc.arabicMeaning || "",
    example: doc.exampleSentence || "",
    forms: wordForms(doc.baseWord || doc.word),
  }));

  return {
    lists: assigned
      .filter((list) => allowedSet.has(list.listId))
      .map((list) => ({
        listId: list.listId,
        title: list.title || list.listId,
        semester: list.semester,
        wordCount: list.wordCount || 0,
      })),
    words,
    total: uniqueTotal.length,
    shown: words.length,
    truncated: uniqueTotal.length > words.length,
  };
};

/**
 * Resolve every enabled source for one student. A source with no eligible words
 * reports `unavailable`, which the rail explains instead of hiding silently.
 */
export const resolveWritingWordSupport = async ({
  schoolId,
  studentId,
  assignment,
  priorTargets = [],
}) => {
  const config = normalizeWordSupport(assignment?.supports?.wordSupport);
  if (!config.spelling.enabled && !config.vocabulary.enabled) {
    return disabled(config);
  }

  const [spelling, vocabulary] = await Promise.all([
    config.spelling.enabled
      ? spellingWords({ schoolId, studentId, config: config.spelling, priorTargets })
      : Promise.resolve([]),
    config.vocabulary.enabled
      ? vocabularyWords({
          schoolId,
          studentId,
          config: config.vocabulary,
        })
      : Promise.resolve(emptyVocabulary()),
  ]);

  return {
    enabled: true,
    spelling: {
      ...config.spelling,
      status: spelling.length ? "available" : "unavailable",
      words: spelling,
    },
    vocabulary: {
      ...config.vocabulary,
      status: vocabulary.words.length ? "available" : "unavailable",
      lists: vocabulary.lists,
      words: vocabulary.words,
      total: vocabulary.total,
      shown: vocabulary.shown,
      truncated: vocabulary.truncated,
    },
  };
};

