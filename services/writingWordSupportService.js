const editDistance = (a, b, limit) => {
  if (Math.abs(a.length - b.length) > limit) return limit + 1;
  const previous = new Array(b.length + 1);
  const current = new Array(b.length + 1);
  for (let j = 0; j <= b.length; j += 1) previous[j] = j;
  for (let i = 1; i <= a.length; i += 1) {
    current[0] = i;
    let best = current[0];
    for (let j = 1; j <= b.length; j += 1) {
      const cost = a[i - 1] === b[j - 1] ? 0 : 1;
      current[j] = Math.min(
        previous[j] + 1,
        current[j - 1] + 1,
        previous[j - 1] + cost,
      );
      if (current[j] < best) best = current[j];
    }
    if (best > limit) return limit + 1;
    for (let j = 0; j <= b.length; j += 1) previous[j] = current[j];
  }
  return previous[b.length];
};

/**
 * Near misses are evidence, never a correction: a longer word must be one edit
 * away, a very long word may be two. Short words are skipped so `the`/`she`
 * does not surface as a misspelling.
 */
const nearMissLimit = (word) => {
  if (word.length >= 8) return 2;
  if (word.length >= 5) return 1;
  return 0;
};

const nearMissesFor = (word, tokens, known) => {
  const limit = nearMissLimit(word);
  if (!limit) return [];
  const found = [];
  for (const token of tokens) {
    // Another offered word, or a form of one, is not a misspelling of this.
    if (token === word || known.has(token)) continue;
    if (editDistance(token, word, limit) <= limit) {
      found.push(token);
      if (found.length === 2) break;
    }
  }
  return found;
};

const wordParts = (row) => {
  const word = normal(row?.word);
  const base = normal(row?.baseWord || "");
  const forms = (
    Array.isArray(row?.forms) && row.forms.length
      ? row.forms
      : wordForms(base || word)
  )
    .map(normal)
    .filter(Boolean);
  return { word, base, forms };
};

/**
 * Compare the submitted text with the words the student was offered. Whole
 * tokens only, case-insensitive; a common inflection of the word counts as
 * using it, and an offered word that is not in the draft is reported as not
 * used instead of disappearing from the evidence.
 */
export const analyzeWordUse = ({ draftText = "", wordSupport = null } = {}) => {
  if (!wordSupport?.enabled) return null;
  const tokens = textTokens(draftText);
  const tokenSet = new Set(tokens);

  const parts = new Map();
  const known = new Set();
  for (const row of [
    ...(wordSupport.spelling?.words || []),
    ...(wordSupport.vocabulary?.words || []),
  ]) {
    const parsed = wordParts(row);
    parts.set(row, parsed);
    if (parsed.word) known.add(parsed.word);
    if (parsed.base) known.add(parsed.base);
    for (const form of parsed.forms) known.add(form);
  }

  const spelling = (wordSupport.spelling?.words || []).map((row) => {
    const { word, forms } = parts.get(row);
    const hits = new Set([word, ...forms].filter(Boolean));
    const hit = [...hits].some((candidate) => tokenSet.has(candidate));
    return {
      word: row.word,
      grade: row.grade || "",
      week: Number(row.week) || 0,
      used: hit,
      count: hit ? tokens.filter((token) => hits.has(token)).length : 0,
      nearMisses: hit ? [] : nearMissesFor(word, tokens, known),
    };
  });

  const vocabulary = (wordSupport.vocabulary?.words || []).map((row) => {
    const { word, base, forms } = parts.get(row);
    const hits = new Set([word, base, ...forms].filter(Boolean));
    const hit = [...hits].some((candidate) => tokenSet.has(candidate));
    return {
      word: row.word,
      listId: row.listId,
      used: hit,
      count: hit ? tokens.filter((token) => hits.has(token)).length : 0,
      nearMisses: hit ? [] : nearMissesFor(word, tokens, known),
    };
  });

  if (!spelling.length && !vocabulary.length) return null;
  return {
    spelling: spelling.map((row) => ({ ...row, teacherDecision: "" })),
    vocabulary: vocabulary.map((row) => ({ ...row, teacherDecision: "" })),
  };
};

/** Teacher decisions are additive: only the named row changes, nothing is scored. */
export const applyWordUseDecisions = ({ evidence, decisions = [] } = {}) => {
  if (!evidence) return [];
  const changed = [];
  for (const incoming of decisions || []) {
    if (!incoming?.word) continue;
    const source = incoming.source === "vocabulary" ? "vocabulary" : "spelling";
    const word = normal(incoming.word);
    const row = (evidence[source] || []).find(
      (candidate) => normal(candidate.word) === word,
    );
    if (!row) continue;
    const decision =
      incoming.decision === "confirmed" || incoming.decision === "rejected"
        ? incoming.decision
        : "";
    if (row.teacherDecision !== decision) {
      row.teacherDecision = decision;
      changed.push(`${source}.${row.word}`);
    }
  }
  return changed;
};
